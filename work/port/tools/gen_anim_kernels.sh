#!/bin/sh
# Generate the kernel bodies of job2025_kernels_native.c from the lifted job
# module (game code: the headers stay out of the repository, like the lift).
#   gen_anim_kernels.sh <jobmod_2025343b09d0_eFE70.bin> <ps3recomp dir> <out dir>
set -e
BIN=$1 RC=$2 OUT=$3
T=$(dirname "$0")
LST=$(mktemp)
python3 "$RC/tools/spu_disasm.py" "$BIN" --base 0x4000 > "$LST"
python3 "$T/kgen.py" "$LST" "$BIN" "$OUT/job2025_kernels_gen.h" \
    k_16320:16320:16A30 k_16A30:16A30:17280 k_17780:17780:179C0 k_179C0:179C0:186A0 \
    k_1A570:1A570:1A870 k_19A20:19A20:1A570 k_1B5F0:1B5F0:1C510 k_1C510:1C510:1D4D0
echo '/* Generated by work/port/tools/kwide.py. Do not edit. */' > "$OUT/job2025_kernels_wide.h"
for c in slerp slerp2 p34; do
    python3 "$T/kwide.py" "$LST" "$BIN" "$OUT/job2025_kernels_wide.h" "$T/kw/$c.json"
done
rm -f "$LST"
