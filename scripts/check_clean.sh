#!/usr/bin/env bash
# Refuse to commit or push anything that is the game or comes from it, and
# anything that looks like a credential. Checks what git would record: the
# index by default, or `--tracked` for every tracked file.
#
#   scripts/check_clean.sh            staged files (pre-commit)
#   scripts/check_clean.sh --tracked  all tracked files (pre-push, CI)
set -u
cd "$(git rev-parse --show-toplevel)" || exit 2
if [ "${1:-}" = "--tracked" ]; then
    files=$(git ls-files)
else
    files=$(git diff --cached --name-only --diff-filter=ACMR)
fi
fail=0
bad() { echo "check_clean: $1" >&2; fail=1; }

for f in $files; do
    [ -f "$f" ] || continue
    base=$(basename "$f")
    lower=$(printf '%s' "$base" | tr 'A-Z' 'a-z')
    # Game and firmware formats, and anything named like the title's files.
    case "$lower" in
        *.elf|*.self|*.sprx|*.prx|*.bin|*.iso|*.pkg|*.psarc|*.rap|*.edat|*.sdat|*.sfo|*.pup|*.dat|*.trp)
            bad "$f: game or firmware file type" ;;
        eboot*) bad "$f: named like the game's executable" ;;
    esac
    # Size: nothing here should be large; lifted code and dumps are. The
    # toolkit patch is the one big text file.
    size=$(stat -c %s "$f")
    limit=1048576
    case "$f" in work/patches/*.patch) limit=8388608 ;; esac
    [ "$size" -gt "$limit" ] && bad "$f: larger than $limit bytes ($size)"
    # Binary content.
    if [ "$size" -gt 0 ] && ! grep -Iq . "$f"; then bad "$f: binary file"; fi
    # Code lifted from the game: the names the lifters give its SPU images
    # (job modules, plugins, the policy module) and its PPU functions.
    # (definitions only: tools name them in templates and comments)
    if grep -qE "^[+ ]?void ((jobmod_[0-9a-f]{12}_e[0-9A-F]+|wws_plugin_[0-9A-F]{8}|wws_pm)_spu_func_[0-9A-F]+|func_[0-9A-F]{8})\(" "$f"; then
        bad "$f: code lifted from the game"
    fi
    # Lifter output anywhere but the toolkit patch, whose own tests hold
    # synthetic examples of it.
    case "$f" in work/patches/*.patch) ;; *)
        if grep -qE "^/\* .*(Auto-generated by (spu|ppu)_lifter|GENERATED by work/tools/lift_spu.py)" "$f"; then
            bad "$f: lifter output"
        fi ;;
    esac
    # Credentials.
    if grep -qiE "(api[_-]?key|secret|token|passw(or)?d)[\"' ]*[:=][\"' ]*[A-Za-z0-9/+_-]{20,}|-----BEGIN [A-Z ]*PRIVATE KEY-----" "$f"; then
        bad "$f: looks like it holds a credential"
    fi
done
[ "$fail" -eq 0 ] && echo "check_clean: ok ($(printf '%s\n' $files | grep -c .) files)"
exit "$fail"
